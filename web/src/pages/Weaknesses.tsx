import { Link } from "react-router-dom";

interface WeaknessProps {
  id: string;
  severity: "high" | "medium" | "low";
  title: string;
  children: React.ReactNode;
}

const SEVERITY_STYLES = {
  high: "border-red-300 bg-red-50",
  medium: "border-amber-300 bg-amber-50",
  low: "border-slate-300 bg-slate-50",
};

const SEVERITY_BADGE = {
  high: "bg-red-100 text-red-700",
  medium: "bg-amber-100 text-amber-700",
  low: "bg-slate-200 text-slate-600",
};

function Weakness({ id, severity, title, children }: WeaknessProps) {
  return (
    <div id={id} className={`border-l-4 rounded-r-lg p-5 mb-4 ${SEVERITY_STYLES[severity]}`}>
      <div className="flex items-start gap-3 mb-2">
        <span className={`text-xs font-semibold px-2 py-0.5 rounded ${SEVERITY_BADGE[severity]}`}>
          {severity.toUpperCase()}
        </span>
        <h3 className="text-base font-semibold text-slate-800 -mt-0.5">{title}</h3>
      </div>
      <div className="text-sm text-slate-700 leading-relaxed space-y-2 ml-[52px]">
        {children}
      </div>
    </div>
  );
}

export function Weaknesses() {
  return (
    <div className="max-w-3xl">
      <h1 className="text-2xl font-bold text-slate-800 mb-1">Known Weaknesses</h1>
      <p className="text-sm text-slate-500 mb-6">
        An honest accounting of limitations, untested assumptions, and known failure modes.
        Severity reflects potential impact on conclusions if the weakness turns out to matter.
      </p>

      <h2 className="text-lg font-semibold text-slate-700 mb-3 mt-8 border-b border-slate-200 pb-2">
        Methodological Weaknesses
      </h2>

      <Weakness id="cv-bias" severity="high" title="Cross-validation is a failed instrument">
        <p>
          Held-out CV prefers the independent-nudge rival by 253 log-score units. This is
          demonstrated as a <strong>bias</strong> in synthetic checks: CV picks the wrong model even
          on data generated by CLAIM (3/3 seeds). The mechanism is understood — strict models call
          held-out children impossible when hidden-gene estimation fails on the training fold — but
          no fix has been implemented. The cv_ll field should not be cited as evidence about mechanism.
        </p>
      </Weakness>

      <Weakness id="floor" severity="high" title="Floored score is not a proper likelihood">
        <p>
          The fitting criterion replaces probabilities below 10<sup>-15</sup> with a fixed floor.
          This is not a proper likelihood: it hides information about <em>how</em> impossible a child
          is (15 impossible children under R=140 all get the same -34.5 penalty), and it lacks an
          observation-error model. One transcription error can look exactly like a rare mechanism.
          A proper contamination likelihood is specified in the methodology but not yet implemented.
        </p>
      </Weakness>

      <Weakness id="model-space" severity="high" title="Limited model space (30 variants of one architecture family)">
        <p>
          All 30 models share the same hidden-gene architecture — they vary one axis at a time
          (nudge range, shape, display rules). No structurally different architectures are tested:
          continuous latent states, epistasis, spatial inheritance, phenotype-only models, or
          three-gene models. Of 255 possible display-rule combinations, only 12 are tested.
          The CLAIM model wins within its family, but might lose to an untested architecture.
        </p>
      </Weakness>

      <Weakness id="same-data" severity="medium" title="All analyses use the same 692 children">
        <p>
          The model was constructed, tuned, and evaluated on the same dataset. Every sensitivity
          analysis, anomaly investigation, and parameter sweep re-analyzes the same observations.
          This is the multiple-comparisons version of overfitting — eventually some explanation
          will fit well by adaptive search. The 692-child dataset should be treated as exploratory;
          confirmatory validation requires newly collected data.
        </p>
      </Weakness>

      <Weakness id="model-recovery" severity="medium" title="Model recovery (9/9) is self-consistency, not robustness">
        <p>
          Synthetic data tests verify that the fitter recovers the true model when the generating
          mechanism is one of the candidates. This checks code correctness, not robustness.
          No adversarial simulation study has been done: generating from architectures not in the
          candidate set and measuring the false-confidence rate when CLAIM is incorrectly selected.
        </p>
      </Weakness>

      <Weakness id="latent-confound" severity="medium" title="Architecture confounded with latent optimization">
        <p>
          Every model gets hidden parent genes fitted independently per litter. A mechanism may
          score well because its latent representation is easier to optimize, not because it
          better describes the game. The shared-parent litters (Hive1a/1b/1c sharing Start 1 and
          Start 2) provide a partial test but are not exploited for cross-litter transfer.
        </p>
      </Weakness>

      <h2 className="text-lg font-semibold text-slate-700 mb-3 mt-8 border-b border-slate-200 pb-2">
        Structural Assumptions (Untested)
      </h2>

      <Weakness id="coin-flip" severity="medium" title="Fair 50/50 coin flip assumed but never tested">
        <p>
          Inheritance is modeled as an unbiased coin flip per gene. It could be biased (60/40),
          correlated across genes (all 8 from the same parent), or depend on proximity, tree age,
          or species. No biased-coin variant has been fitted — if one fits better, we would not know.
        </p>
      </Weakness>

      <Weakness id="nudge-shape" severity="low" title="Nudge distribution tested only against triangular">
        <p>
          The uniform nudge beats triangular by 86 log-score units, but Gaussian, Laplacian, beta,
          and empirical distributions are untested. With most nudges invisible (hidden gene changes
          not affecting the display value), the data may lack power to distinguish shapes with
          similar standard deviations.
        </p>
      </Weakness>

      <Weakness id="slot-preserving" severity="low" title="Slot-preserving inheritance assumed">
        <p>
          Child gene slot 1 is assumed to always come from a parent's slot 1. If slot swapping is
          possible, identifiability changes. For min/max rules, swapping g1 and g2 produces
          observationally different offspring distributions; for the mean rule, it is equivalent.
          Partially testable but not tested.
        </p>
      </Weakness>

      <Weakness id="clamping" severity="low" title="Boundary handling (clamping) is untested">
        <p>
          Genes exceeding [0, 1000] after mutation are clamped. Alternatives (wrapping: 1050 becomes
          50; reflecting: 1050 becomes 950) would produce different distributions for extreme-valued
          parents. A gene at 900 has a ~16.6% chance of hitting the upper boundary. Not tested.
        </p>
      </Weakness>

      <h2 className="text-lg font-semibold text-slate-700 mb-3 mt-8 border-b border-slate-200 pb-2">
        Data Weaknesses
      </h2>

      <Weakness id="ascertainment" severity="medium" title="Ascertainment bias is unquantified">
        <p>
          It is not established whether the 692 children are complete offspring sequences or a
          selected subset. If players disproportionately recorded interesting species, successful
          crosses, or unusual children, then every inferred frequency, mutation rate, clone fraction,
          and distributional test could be biased. Raw logs have not been audited for completeness.
        </p>
      </Weakness>

      <Weakness id="parent-assignment" severity="medium" title="Parent assignment taken at face value">
        <p>
          Recorded parent identities are assumed correct. If the game's parent-selection mechanism
          differs from what was recorded (wrong parent, third-tree interference, coordinate edge
          cases with the +/-19 range), the model fits noise as signal. The argument that "CLAIM
          has 0 impossible children" is partly circular: hidden genes are optimized using those
          same children and can accommodate some parent mistakes.
        </p>
      </Weakness>

      <Weakness id="hive1b" severity="medium" title="Hive1b cloning anomaly is unexplained">
        <p>
          34% of Hive1b's children are best explained as full parent copies with a standard nudge.
          No other litter exhibits this (Hive1a, 1c: 0%). Hive1b is the only litter whose parents
          stood in different regions. Why it copies is unknown — it could be a game mechanic tied
          to distance, a bug, or a data artifact.
        </p>
      </Weakness>

      <h2 className="text-lg font-semibold text-slate-700 mb-3 mt-8 border-b border-slate-200 pb-2">
        Non-Identifiability
      </h2>

      <Weakness id="length-id" severity="low" title="Length display rule is non-identifiable">
        <p>
          "Length = gene 1" cannot be distinguished from "Length = min(g1, g2)" by fit alone.
          The rival gains 59 on real data and 54-66 on synthetic data where gene 1 is the truth.
          Held-out scoring prefers gene 1 by 392, but CV is known to be biased (see above).
          Only gene 1 is ever observed; the second Length gene is inferred from the nudge rate.
        </p>
      </Weakness>

      <Weakness id="color-id" severity="low" title="Color gene split is non-identifiable">
        <p>
          Color uses the mean display rule, so only the sum of the two genes is observable.
          The split between g1 and g2 is unconstrained. Clamping at 0/1000 for Color genes
          is therefore approximate.
        </p>
      </Weakness>

      <Weakness id="hidden-bounded" severity="low" title="Hidden genes are often only bounded, not exactly identified">
        <p>
          On synthetic data, the fitter recovers 68% of hidden Sweet/Size genes exactly.
          The rest are known only as "at least X" or "at most X." For structurally
          non-identifiable parameters (Length g2, Color gene split), recovery should be
          reported on observational-equivalence classes, not exact coordinates.
        </p>
      </Weakness>

      <div className="mt-10 p-5 bg-slate-100 rounded-lg border border-slate-200">
        <p className="text-sm text-slate-600 italic">
          This is a fit to observed data. It does not prove this is the game's code.
          Other mechanisms that produce the same probabilities would fit equally well.
          See the{" "}
          <Link to="/methods" className="text-teal-600 hover:text-teal-700 underline">
            full methodology
          </Link>{" "}
          for detailed discussion of each weakness and proposed mitigations.
        </p>
      </div>
    </div>
  );
}
